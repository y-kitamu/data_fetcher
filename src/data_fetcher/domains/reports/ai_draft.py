"""Ask Claude Code (`claude -p`) to draft the human-written parts of an
initial/review report generated by scripts/new_report.py.

Claude researches the company on the web (and in the local snapshot/tables)
and edits the report Markdown in place: it replaces the 「（記入）」 placeholders
in the body with drafts marked 「（AI下書き・要確認）」, cites a source for every
fact in a 「出典（AI下書き）」 section, and writes judgement items (thesis,
ratings.final, predictions, kill_criteria, ...) only as proposals in an
「AI案」 section. The frontmatter, the snapshot-summary block and the
`<!-- auto:xxx -->` markers must stay untouched; `validate_draft` checks that
afterwards and the caller restores the original text if they changed.

Only uncommitted reports are drafted, because a committed report's body must
not be changed (reports/README.md).
"""

from __future__ import annotations

import datetime as dt
import json
import re
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal

from ...core.constants import PROJECT_ROOT
from .writer import _SUMMARY_END, _SUMMARY_START, split_frontmatter

ReportKind = Literal["initial", "review"]

CLAUDE_MODEL = "opus"
TIMEOUT_SECONDS = 3600
ALLOWED_TOOLS = "Read,Grep,Glob,Edit,WebSearch,WebFetch"

_REPORT_NAME_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})_.+_(initial|review)\.md$")
_AUTO_MARKER_RE = re.compile(r"<!-- auto:[^>]*-->")

OUTPUT_SCHEMA = {
    "type": "object",
    "properties": {
        "summary": {"type": "string"},
        "filled_sections": {"type": "array", "items": {"type": "string"}},
        "unresolved": {"type": "array", "items": {"type": "string"}},
        "sources": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "title": {"type": "string"},
                    "url": {"type": "string"},
                    "accessed": {"type": "string"},
                },
                "required": ["title", "url", "accessed"],
            },
        },
    },
    "required": ["summary", "filled_sections", "unresolved", "sources"],
}


class DraftError(Exception):
    pass


@dataclass
class Source:
    title: str
    url: str
    accessed: str


@dataclass
class DraftResult:
    summary: str = ""
    filled_sections: list[str] = field(default_factory=list)
    unresolved: list[str] = field(default_factory=list)
    sources: list[Source] = field(default_factory=list)
    error: str | None = None


def report_kind(md_path: Path) -> ReportKind:
    match = _REPORT_NAME_RE.match(md_path.name)
    if match is None:
        raise DraftError(
            f"initial / review レポートのファイル名ではありません: {md_path.name}"
        )
    return match.group(2)  # type: ignore[return-value]


def find_target_report(ticker_dir: Path, as_of: str | None = None) -> Path:
    """`as_of` の日付の initial / review、省略時はファイル名の日付順で最新のものを返す。"""
    candidates = (
        sorted(
            p
            for p in ticker_dir.glob("*.md")
            if _REPORT_NAME_RE.match(p.name)
            and (as_of is None or p.name.startswith(f"{as_of}_"))
        )
        if ticker_dir.exists()
        else []
    )
    if not candidates:
        target = f"{as_of} の " if as_of else ""
        raise DraftError(
            f"{ticker_dir} に {target}initial / review レポートが見つかりません。"
            "先に new_report.py で生成してください。"
        )
    if len(candidates) > 1 and as_of is not None:
        raise DraftError(
            f"{as_of} のレポートが複数あります: {[p.name for p in candidates]}"
        )
    return candidates[-1]


def _related_paths(md_path: Path) -> tuple[Path, Path]:
    stem = md_path.name.rsplit("_", 1)[0]  # YYYY-MM-DD_<ticker>
    snapshot_path = md_path.with_name(f"{stem}_snapshot.json")
    return snapshot_path, md_path.with_name(f"{stem}_tables.md")


def _parent_initial(md_path: Path) -> Path | None:
    initials = sorted(
        p for p in md_path.parent.glob("*_initial.md") if p.name < md_path.name
    )
    return initials[-1] if initials else None


def _previous_snapshot(snapshot_path: Path) -> Path | None:
    earlier = sorted(
        p
        for p in snapshot_path.parent.glob("*_snapshot.json")
        if p.name < snapshot_path.name
    )
    return earlier[-1] if earlier else None


def _proposal_items(kind: ReportKind) -> str:
    if kind == "initial":
        return """- thesis（投資仮説 1〜2文）
- ratings の final 案（特に人の判断項目 business_quality / shareholder_policy と、
  auto が null の項目）。各項目に A〜E の案と根拠（rubric.md の基準に沿って）
- predictions 案（2〜3件。claim は「いつまでに・何が・どの水準に」が第三者に判定できる形。
  prob / due / metric も埋める）
- kill_criteria 案（数値で判定できるものは {text, metric, op, value} 形式。metric は
  reports/README.md の「kill_criteria で使える指標」から選ぶ）
- plan 案（tranches / max_position_pct / target_exit / time_stop）
- decision / conviction 案"""
    return """- thesis_status 案（intact / weakened / broken）と根拠
- prediction_updates 案（親 initial の predictions の id ごとに progress / outcome / note）
- rating_changes 案（変わった項目だけ）
- action / action_detail 案
- status 案"""


def build_prompt(md_path: Path, as_of: str, today: dt.date) -> str:
    kind = report_kind(md_path)
    snapshot_path, tables_path = _related_paths(md_path)
    reports_dir = md_path.parent.parent
    related = [
        f"- スナップショット(自動計算の正): {snapshot_path}",
        f"- 数値の表: {tables_path}",
        f"- 評価基準: {reports_dir / 'rubric.md'}",
        f"- レポートの運用ルール・kill_criteria の metric 一覧: {reports_dir / 'README.md'}",
    ]
    if kind == "review":
        parent = _parent_initial(md_path)
        prev_snapshot = _previous_snapshot(snapshot_path)
        if parent is not None:
            related.append(f"- 親の初回レポート(仮説・予測・撤退条件): {parent}")
        if prev_snapshot is not None:
            related.append(f"- 前回のスナップショット: {prev_snapshot}")
    related_lines = "\n".join(related)

    return f"""本日は {today.isoformat()} です。
企業分析レポート {md_path} （種別: {kind}、基準日 as_of: {as_of}）は、
scripts/new_report.py が自動計算の値だけを埋めて生成した雛形です。
人が記入する前の下書きとして、事実を調査してこのファイルの記入欄を埋めてください。

## 参照するファイル
{related_lines}

まず対象ファイル・スナップショット・表を読み、会社名・業種・財務の状況を把握すること。

## 調査
- 会社の IR（有価証券報告書・決算短信・決算説明資料・中期経営計画・統合報告書）、
  TDnet の適時開示、EDINET、業界団体・官公庁の統計、信頼できる報道などをウェブで調査する。
- 財務数値はスナップショット・表を正とし、ウェブの数値で上書き・再計算しない
  （補足として引用する場合は出典を付ける）。

## 出典（必須）
- 事実を述べる文には必ず脚注 `[^1]` `[^2]` … を付け、ファイル末尾に `## 出典（AI下書き）` 節を
  作って次の形式で列挙すること:
  `[^1]: <資料タイトル> — <発行元>, <URL>（公表日 YYYY-MM-DD / 参照日 {today.isoformat()}）`
  公表日が分からなければ「公表日不明」と書く。
- ローカルのファイル（スナップショット等）から書いた内容はファイルパスを出典にする。
- 実際に開いて内容を確認したページだけを出典にすること。記憶や推測で URL を書かない。
- 出典を確認できない事実は書かず、「（要確認: 出典未確認）」と残す。
- 推測・評価は文中に「（推測）」と明記し、事実と区別する。

## 書き方
- 本文の「（記入）」の箇所を、「（AI下書き・要確認）」で始まる文章に置き換える
  （人が「AI下書き」で検索して確認箇所を追えるようにするため）。表のセル内の「（記入）」も同様。
- 2.4 の「利益を振らせる変数」の表は、例の行を実際の変数に置き換えてよい。
- 日本語で、簡潔に、各欄の HTML コメントのガイドに沿って書く。
- 調べても分からない欄は「（AI下書き・要確認）調査で確認できず。」と書いて残す。

## 判断項目（提案のみ）
投資判断に関わる項目は人が決めるため、frontmatter には書かない。代わりにファイル末尾
（`## 出典（AI下書き）` の直前）に `## AI案（要確認・frontmatter未反映）` 節を作り、次の案を
frontmatter にそのままコピーできる YAML 片（```yaml のコードブロック）と、根拠の短い説明で書く:
{_proposal_items(kind)}
本文中の判断を求める欄（例: 「評価の補足」「総括」「判断」）も「（AI下書き・要確認）」として
案を書いてよいが、断定せず根拠を示すこと。

## 変更してはいけない箇所
- frontmatter（先頭の `---` から `---` まで）全体。1文字も変更しない。
- `<!-- snapshot-summary:start ... -->` から `<!-- snapshot-summary:end -->` までの中身。
- `<!-- auto:... -->` のコメントと、各セクションのガイド用 HTML コメント。
- 対象ファイル以外のファイル（スナップショット・表・テンプレート等）は一切編集しない。

## 制約
- git の操作はしない。ユーザーへの質問はせず、最後まで自力で判断して書き終えること。

## 出力
編集を終えたら、指定の JSON スキーマで回答すること（日本語）。
- summary: 下書きの要約（2〜4文）
- filled_sections: 下書きを書いた節の見出し
- unresolved: 確認できなかった事項・人が確認すべき点
- sources: 出典に挙げた資料（title / url / accessed）
"""


def validate_draft(before: str, after: str) -> list[str]:
    """下書きで変更してはいけない箇所が変わっていないか確認し、違反の一覧を返す。"""
    problems: list[str] = []
    fm_before, body_before = split_frontmatter(before)
    try:
        fm_after, body_after = split_frontmatter(after)
    except ValueError:
        return ["frontmatter が壊れています"]
    if fm_before != fm_after:
        problems.append("frontmatter が変更されています")

    def summary_block(body: str) -> str | None:
        start = body.find(_SUMMARY_START)
        end = body.find(_SUMMARY_END)
        return body[start:end] if start != -1 and end > start else None

    if summary_block(body_before) != summary_block(body_after):
        problems.append("snapshot-summary ブロックが変更されています")
    after_markers = set(_AUTO_MARKER_RE.findall(body_after))
    missing = [
        m for m in _AUTO_MARKER_RE.findall(body_before) if m not in after_markers
    ]
    if missing:
        problems.append(f"auto コメントが消えています: {missing}")
    return problems


def _parse_output(stdout: str) -> DraftResult:
    envelope = json.loads(stdout)
    if envelope.get("is_error"):
        return DraftResult(error=f"claude returned an error: {envelope.get('result')}")
    payload = envelope.get("structured_output")
    if payload is None:
        payload = json.loads(envelope.get("result", ""))
    return DraftResult(
        summary=payload["summary"],
        filled_sections=list(payload.get("filled_sections", [])),
        unresolved=list(payload.get("unresolved", [])),
        sources=[Source(**s) for s in payload.get("sources", [])],
    )


def _invoke_claude(prompt: str, md_path: Path) -> DraftResult:
    claude_path = shutil.which("claude")
    if claude_path is None:
        return DraftResult(error="claude コマンドが見つかりません")
    cmd = [
        claude_path,
        "-p",
        prompt,
        "--model",
        CLAUDE_MODEL,
        "--permission-mode",
        "dontAsk",
        f"--allowedTools={ALLOWED_TOOLS}",
        "--output-format",
        "json",
        "--json-schema",
        json.dumps(OUTPUT_SCHEMA),
        "--no-session-persistence",
    ]
    reports_dir = md_path.resolve().parent.parent
    if not reports_dir.is_relative_to(PROJECT_ROOT.resolve()):
        cmd += ["--add-dir", str(reports_dir)]
    try:
        proc = subprocess.run(
            cmd,
            cwd=PROJECT_ROOT,
            capture_output=True,
            text=True,
            timeout=TIMEOUT_SECONDS,
            stdin=subprocess.DEVNULL,
        )
    except subprocess.TimeoutExpired:
        return DraftResult(error=f"{TIMEOUT_SECONDS} 秒でタイムアウトしました")
    except OSError as e:
        return DraftResult(error=f"claude の起動に失敗しました: {e}")
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout).strip()[-500:]
        return DraftResult(
            error=f"claude が終了コード {proc.returncode} で失敗しました: {detail}"
        )
    try:
        return _parse_output(proc.stdout)
    except (ValueError, KeyError, TypeError) as e:
        return DraftResult(error=f"claude の出力を解析できませんでした: {e}")


def run_draft(md_path: Path, as_of: str, today: dt.date | None = None) -> DraftResult:
    """md_path を Claude に下書きさせる。変更してはいけない箇所が変わっていたら
    元の内容に戻して error を返す。"""
    today = today or dt.date.today()
    before = md_path.read_text(encoding="utf-8")
    result = _invoke_claude(build_prompt(md_path, as_of, today), md_path)
    after = md_path.read_text(encoding="utf-8")
    if after != before:
        problems = validate_draft(before, after)
        if problems:
            md_path.write_text(before, encoding="utf-8")
            result.error = (
                "変更してはいけない箇所が変更されたため、元の内容に戻しました: "
                + " / ".join(problems)
            )
    elif result.error is None:
        result.error = "ファイルが変更されませんでした"
    return result
